"""Navigation and evaluation-table interactions against the local server."""
import os
import tempfile
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE=os.getenv('IAJEDREZ_TEST_URL','http://127.0.0.1:8765')
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1440,'height':900})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('console',lambda m:errors.append(m.text) if m.type=='error' else None)
    for game,count,last in [('entrevista',54,'54'),('mauricio',19,'19'),('gemini',34,'34.')]:
        page.goto(BASE+'/?game='+game)
        expect(page).to_have_title('IAjedrez — Análisis de partida')
        expect(page.locator('#view-menu button')).to_have_text(['Evaluar','Concatenar','Aprender'])
        expect(page.locator('.evaluation-table')).to_be_visible()
        expect(page.locator('.results-table')).to_have_count(1)
        expect(page.locator('#first')).to_be_disabled()
        page.locator('#last').click()
        expect(page.locator('#current-move')).to_contain_text(last)
        expect(page.locator('#last')).to_be_disabled()
        page.locator('#first').click()
        expect(page.locator('#current-move')).to_have_text('Posición inicial')
        page.locator('[data-filter="good"]').click()
        badge=page.locator('#tree [data-error-ply]').last
        ply=badge.get_attribute('data-error-ply')
        badge.focus()
        badge.press('Enter')
        expect(page.locator('[data-filter="errors"]')).to_have_attribute('aria-pressed','true')
        target=page.locator(f'.highlight-row [data-jump="{ply}"]')
        expect(target).to_be_focused()
        expect(target).to_be_in_viewport()
        expect(page.locator(f'#tree [data-ply="{ply}"]')).to_have_attribute('aria-current','step')
        expect(page.locator('.highlight-row')).to_contain_text('Pendiente')
        page.locator('#move-subtitle [data-error-ply]').click()
        expect(target).to_be_focused()
        target.press('Enter')
        expect(page.locator('[data-view="chain"]')).to_have_attribute('aria-pressed','true')
        page.locator('[data-go-back]').click()
        expect(target).to_be_in_viewport()
        expect(page.locator('.highlight-row')).to_contain_text('Revisada')
        page.locator('[data-next-pending]').click()
        expect(page.locator('.highlight-row [data-jump]')).to_be_focused()
        expect(page.locator('.highlight-row')).to_contain_text('Pendiente')
        page.locator('[data-next-cat]').first.click()
        expect(page.locator('.highlight-row [data-jump]')).to_be_focused()
        first=page.locator('.evaluation-table tbody tr').first
        expect(first.locator('.eval-score')).to_have_count(2)
        first.locator('[data-preview]').first.click()
        expect(page.locator('[data-view="evaluate"]')).to_have_attribute('aria-pressed','true')
        expect(page.locator('.board-arrows')).to_be_visible()
        expect(page.locator('#move-subtitle')).to_contain_text('Variante')
        page.locator('#next').click()
        expect(page.locator('#move-subtitle')).to_contain_text('2/')
        page.locator('#last').click()
        expect(page.locator('.board-arrows')).to_have_count(0)
        expect(page.locator('#current-move')).to_contain_text(last)
        page.locator('[data-filter="all"]').click()
        expect(page.locator('.evaluation-table tbody tr:not(.group-row)')).to_have_count(count)
        assert page.locator('.evaluation-table thead th').evaluate_all('(es)=>es.map(e=>{const c=e.cloneNode(true);c.querySelectorAll(".type-legend").forEach(t=>t.remove());return c.textContent})')==['Jugada','Tipo ?','Consejo','Explicación']
        page.locator('.type-help').hover()
        expect(page.locator('#type-legend')).to_contain_text('Brillante')
        page.keyboard.press('Escape')
        page.locator('.evaluation-table [data-preview]').first.click()
        expect(page.locator('[data-view="evaluate"]')).to_have_attribute('aria-pressed','true')
        expect(page.locator('.board-arrows')).to_be_visible()
        page.locator('[data-exit-mode]').click()
        page.locator('.evaluation-table [data-jump]').first.click()
        expect(page.locator('[data-view="chain"]')).to_have_attribute('aria-pressed','true')
    page.goto(BASE+'/?game=entrevista')
    page.locator('#tree [data-error-ply="89"]').click()
    expect(page.locator('.highlight-row [data-jump="89"]')).to_be_in_viewport()
    page.screenshot(path=str(Path(tempfile.gettempdir())/'iajedrez-evaluation.png'))
    page.locator('[data-preview="89"]').click()
    expect(page.locator('#current-move')).to_contain_text('Cg7+')
    page.locator('[data-exit-mode]').click()
    page.set_viewport_size({'width':390,'height':844})
    page.locator('[data-panel="tree-panel"]').click()
    page.locator('#tree [data-error-ply="89"]').click()
    expect(page.locator('.highlight-row [data-jump="89"]')).to_be_in_viewport()
    page.locator('.view-settings > summary').click()
    page.locator('#vision-sim').select_option('deuteranopia')
    page.locator('.view-settings > summary').click()
    expect(page.locator('.highlight-row .type-name')).to_be_visible()
    expect(page.locator('#first')).to_be_visible()
    expect(page.locator('#last')).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    sizes=page.locator('#board .square').evaluate_all('(es)=>es.map(e=>{const r=e.getBoundingClientRect();return [r.width,r.height]})')
    assert all(abs(w-h)<1 for w,h in sizes)
    page.screenshot(path=str(Path(tempfile.gettempdir())/'iajedrez-evaluation-mobile.png'))
    explanation=page.locator('.highlight-row .mobile-explanation')
    explanation.locator('summary').click()
    expect(explanation).to_have_attribute('open','')
    expect(explanation).to_contain_text('Cxc7')
    assert not errors,errors
    print('PASS: all three studies, endpoint navigation, separate cell actions, evaluations, legend, arrows, return, mobile; no JS errors')
    browser.close()
